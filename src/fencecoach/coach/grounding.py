"""Small evidence summaries and checks for known unsupported coaching claims.

These checks catch specific failure modes; they are not a technique evaluator or
a proof that every sentence generated by a model is correct.
"""

from __future__ import annotations

import re

from fencecoach.coach.analysis import build_coaching_brief


def evidence_summary(request, metrics):
    brief = build_coaching_brief(request.model_copy(update={"metrics": list(metrics)}))
    topic = brief["requested_topic"]
    patterns = brief["patterns"]
    if topic == "lunge":
        patterns = [item for item in patterns if item["topic"] != "recovery consistency"]
        actionable = [item for item in patterns if item["priority"] in {"high", "review"}]
        if actionable:
            patterns = actionable
    elif topic in {"knee", "arm", "recovery"}:
        wanted = {
            "knee": "front knee through the lunge",
            "arm": "foil arm timing",
            "recovery": "recovery consistency",
        }[topic]
        patterns = [
            item
            for item in patterns
            if item["topic"] == wanted
            or (topic == "arm" and item["topic"] == "weapon arm at the finish")
        ]
    return {
        "question_topic": topic,
        "capture_context": brief["capture_context"],
        "supported_observations": [
            item["observation"].replace(" reps", " measured intervals") for item in patterns
        ],
        "possible_experiments": [
            {
                "topic": item["topic"],
                "cue": item["practice_focus"],
                "condition": "An optional experiment, not a detected fault. Retrieve guidance before recommending it.",
            }
            for item in patterns
            if item["priority"] in {"high", "review"}
        ],
        "not_established": [
            "Whether knee bend is too shallow, too deep, or technically correct.",
            "An ideal knee angle, beginner reference range, or a need for constant knee angles.",
            "Balance, spinal curvature, blade contact, attack intent, or right of way.",
            "Verified lunge counts or action labels from timing windows alone.",
            "Arm extension at onset and peak does not measure which moved first: hand or foot.",
        ],
        "answer_direction": (
            "Lead with the strongest supported observation and its timestamp, then explain "
            "what to check and one practical experiment. Separate an observation from a fault. "
            "If no fault can be identified, explain the exact missing measurement rather than "
            "a generic pass/fail refusal. Do not manufacture knee-depth or consistency advice."
        ),
    }


def unsupported_claims(reply, metrics=()):
    """Conservative checks for known errors, with local negation handling."""
    issues = []
    metrics = list(metrics)
    if metrics:
        values = {float(m.value) for m in metrics}
        values.update(float(m.value) / 1000 for m in metrics if m.unit == "ms")
        values.update(
            float(t) / 1000 for m in metrics for t in (m.start_ms, m.end_ms) if t is not None
        )
        # Only angle/ratio measurement claims: drill doses and useful time spans
        # need a separate semantic judge, rather than treating every digit alike.
        numeric = re.findall(
            r"(?<![\w-])(\d+(?:\.\d+)?)\s*(?:degrees?|deg\b|°|ratio\b|milliseconds|ms\b|seconds|s\b)",
            reply.lower(),
        )
        if any(
            not any(abs(float(n) - v) <= max(0.1, abs(v) * 0.01) for v in values) for n in numeric
        ):
            issues.append("A reported measurement or timestamp is absent from supplied evidence.")
    peak_times = {
        round(metric.start_ms / 1000, 2)
        for metric in metrics
        if metric.name.endswith("_at_peak") and metric.start_ms is not None
    }
    for match in re.finditer(r"\b(?:start|onset)\s*\(?\s*(\d+(?:\.\d+)?)\s*s\b", reply.lower()):
        if round(float(match.group(1)), 2) in peak_times:
            issues.append("A supplied peak timestamp was mislabeled as movement onset.")
    sentences = re.split(r"(?<=[.!?])\s+|\n+|;|\b(?:but|however|so)\b", reply.lower())
    rules = (
        (
            r"\byour (?:posture|torso|position|movement) (?:was|is|remained|looked|matches)\b.{0,50}\b(?:controlled|balanced|stable)\b",
            "Pose geometry does not establish demonstrated control or balance.",
        ),
        (
            r"\b(?:your|you|the rear arm|your rear arm)\b.{0,75}\b(?:maintaining balance|maintained balance|was balanced|is balanced|lost balance)\b",
            "The supplied pose geometry does not establish observed balance.",
        ),
        (
            r"\b(?:knee|knees)\b.{0,90}\b(?:over[ -]?rotat\w*|under[ -]?rotat\w*|neutral range)\b",
            "A projected knee angle does not establish knee rotation or a neutral angle range.",
        ),
        (
            r"\b(?:avoid|prevent|reduce the risk of)\b.{0,35}\binjur\w*\b",
            "These measurements do not establish injury risk or injury prevention.",
        ),
        (
            r"\b(?:knee|knees)\b.{0,65}\b(?:inward|inwards)\b",
            "Do not instruct inward knee movement.",
        ),
        (
            r"\b(?:bend (?:your (?:knees?|legs?) )?more|bend (?:your (?:knees?|legs?) )?deeper|bend (?:your|the) (?:front )?knees? (?:more|deeper)|increase (?:your )?knee bend|deeper (?:knee )?bend|knees? (?:should|needs? to) (?:be )?bend(?:ing)? more|knees? (?:is|are) too (?:straight|bent)|not bending (?:your knees? )?enough)\b",
            "Knee-depth corrections are not established by these measurements.",
        ),
        (
            r"\b(?:reasonable|normal|ideal|correct|optimal)\b.{0,40}\b(?:range|angle|degrees?|beginner)\b",
            "No validated ideal or beginner angle range is available.",
        ),
        (
            r"\b(?:knee|angle)\b.{0,45}\b(?:too high|too low|lower it to|raise it to)\b",
            "No validated angle target or depth verdict is available.",
        ),
        (
            r"\b(?:knee|leg)\b.{0,80}\b(?:indicate|suggest)\b.{0,50}\b(?:arm|hand) extension\b",
            "Knee geometry does not establish a weapon-arm correction.",
        ),
        (
            r"\b(?:maintain|keep|hold|consistent)\b.{0,45}\b(?:knee angle|angle throughout|same angle|constant angle)\b",
            "A constant knee angle is not a supported goal for a lunge.",
        ),
        (
            r"\b(?:maintain|keep|hold)\b.{0,35}\b(?:straight arm|arm straight)\b",
            "Do not turn a comparison into a prescribed fixed arm position.",
        ),
        (
            r"\b(?:indicate|suggest|show)\b.{0,60}\b(?:adjust your timing|late extension|extend earlier)\b",
            "Arm shape alone does not establish a timing fault.",
        ),
        (
            r"\b(?:i (?:watched|saw)|watching your video|i can see (?:in|from) (?:your|the) (?:video|clip))\b",
            "The coach has measurements, not visual access to frames.",
        ),
        (
            r"\b(?:your (?:lunge|technique|form) (?:is|looks) (?:correct|perfect)|your arm (?:is|was) (?:too late|late)|you (?:extend|extended) (?:your arm )?too late)\b",
            "The available measurements do not establish that technique verdict.",
        ),
        (
            r"\b(?:across|completed|performed|did|counted|detected)\s+(?:\d+|one|two|three|four|five|six|seven|eight|nine|ten)\s+(?:lunges|reps|repetitions)\b",
            "Describe measured intervals, not a verified action count.",
        ),
    )
    for sentence in sentences:
        # A statement explaining why a conclusion cannot be made is not advice.
        if re.search(
            r"\b(?:cannot|can't|don't|do not|doesn't|does not|not enough|not established|won't|wouldn't)\b",
            sentence,
        ):
            continue
        for pattern, issue in rules:
            if re.search(pattern, sentence) and issue not in issues:
                issues.append(issue)
    if re.search(
        r"\b(?:would you mind|may i|can i|is it okay if i)\b.{0,90}\b(?:analy[sz]e|measurements|inspect|review your|read your)\b",
        reply.lower(),
    ):
        issues.append(
            "Reading supplied session evidence is authorized; answer now, without a permission request."
        )
    return issues


def assessment_issues(request, reply, metrics):
    """Require a specific reference when answering an actual arm-finish comparison."""
    issues = unsupported_claims(reply, metrics)
    from fencecoach.coach.turns import general_instruction

    if general_instruction(request.question):
        # Keep measurement/claim checks, but don't demand a drill, timestamp or
        # arm-finish comparison for a question about how to perform a movement.
        return issues
    brief = build_coaching_brief(request.model_copy(update={"metrics": list(metrics)}))
    assessment = (
        bool(metrics) and brief["requested_topic"] in {"lunge", "knee", "arm", "recovery"}
    ) or "supported observation" in request.question.lower()
    if assessment:
        # An observation may be all the evidence supports. Requiring a cue and
        # drill on every assessment pressures the writer to invent advice.
        if len(re.findall(r"\d+(?:\.\d+)?\s*(?:degrees?|deg\b|°|ratio\b)", reply, re.I)) > 2:
            issues.append("Assessment dumps measurements instead of selecting one observation.")
        if (
            re.search(
                r"\b(my|this|these|assess|review)\b|supported observation", request.question, re.I
            )
            and any(m.start_ms is not None and m.confidence >= 0.65 for m in metrics)
            and not re.search(r"\b\d+(?:\.\d+)?\s*(?:s\b|seconds\b)", reply)
        ):
            issues.append(
                "A personal assessment needs a supplied timestamp rather than an unanchored correction."
            )
    if brief["requested_topic"] in {"lunge", "arm"}:
        finish = next(
            (p for p in brief["patterns"] if p["topic"] == "weapon arm at the finish"), None
        )
        if finish:
            timestamps = [
                f"{metric.start_ms / 1000:.1f}"
                for metric in metrics
                if metric.metric_id in finish["evidence_ids"] and metric.start_ms is not None
            ]
            if not any(timestamp in reply for timestamp in timestamps):
                issues.append("The answer omitted the actual timestamped arm-finish comparison.")
    return issues


def grounded_fallback(request, metrics):
    """Honest conversational response when a model cannot repair an invalid draft."""
    summary = evidence_summary(request, metrics)
    observations = summary["supported_observations"]
    brief = build_coaching_brief(request.model_copy(update={"metrics": list(metrics)}))
    finish = (
        next(
            (item for item in brief["patterns"] if item["topic"] == "weapon arm at the finish"),
            None,
        )
        if summary["question_topic"] in {None, "lunge", "arm"}
        else None
    )
    if finish:
        candidates = [metric for metric in metrics if metric.metric_id in finish["evidence_ids"]]
        most_bent = min(candidates, key=lambda item: item.value)
        least_bent = max(candidates, key=lambda item: item.value)
        return (
            "The clearest thing to check is your weapon arm at the finish: the elbow is "
            f"more bent at {most_bent.start_ms / 1000:.2f}s than at {least_bent.start_ms / 1000:.2f}s. "
            "Those are peak frames from different attempts.\n\n"
            "If you meant to perform the same simple lunge, compare those frames and try "
            "a slow repeat toward the same target, watching whether you pull the hand "
            "back before finishing. That's something to investigate, not a confirmed fault."
            " This drill helps separate a changing finish from a timing problem."
        )
    arm = next((item for item in observations if "weapon arm continues" in item), None)
    recovery = next((item for item in observations if "recovery intervals" in item), None)
    if arm:
        metric = next((m for m in metrics if "arm" in m.name and m.start_ms is not None), None)
        when = f" Around {metric.start_ms / 1000:.2f}s," if metric else ""
        return (
            f"{when} your weapon arm keeps straightening as the movement progresses. That gives us "
            "something to investigate, but it doesn't show that your hand started too late. "
            "For the timing question, we'd need to compare when the hand and front foot each "
            "begin moving. For a simple solo drill, try a slow hand-then-foot sequence and reset "
            "between attempts. The cue is to explore the sequence deliberately; it isn't a finding that you extend late."
            " This helps you feel the sequence without rushing."
        )
    if recovery:
        metric = next((m for m in metrics if "recovery" in m.name and m.start_ms is not None), None)
        when = (
            f" The interval at {metric.start_ms / 1000:.2f}s is one comparison point."
            if metric
            else ""
        )
        return (
            "The measured return intervals differ across this session."
            + when
            + " That doesn't tell me "
            "whether the returns were uncontrolled or whether you deliberately paused. "
            "Try a slow set with a deliberate reset to the same en-garde position. The cue is "
            "to finish the return before starting again; this helps distinguish a planned pause from a difficult recovery."
        )
    if metrics:
        topic = summary["question_topic"]
        wanted = {"arm": ("arm", "elbow"), "recovery": ("recovery",)}.get(
            topic, ("knee", "stance", "torso")
        )
        relevant = next(
            (
                m
                for m in metrics
                if m.start_ms is not None
                and any(s in m.name for s in wanted)
                and m.confidence >= 0.65
            ),
            None,
        )
        observation = (
            f"At {relevant.start_ms / 1000:.2f}s, the tracked {relevant.name.replace('_', ' ')} "
            f"is {relevant.value:g} {relevant.unit}. "
            if relevant
            else f"There is no reliable {topic or 'movement'} measurement for a fault finding here. "
        )
        if relevant and "median" in relevant.name:
            observation = f"Over the measured span from {relevant.start_ms / 1000:.2f}s to {relevant.end_ms / 1000:.2f}s, the {relevant.name.replace('_', ' ')} is {relevant.value:g} {relevant.unit}. "
        return (
            observation
            + ("That is a tracked estimate, rather than a correctness score. " if relevant else "")
            + "For your next slow solo set, cue yourself to finish toward the same target and reset fully between attempts. "
            "Repeat that drill slowly and compare the start and finish frames afterward. This helps make the repetitions comparable; "
            "it doesn't establish that you need a deeper bend or earlier extension."
        )
    return (
        "I don't have usable movement evidence for that assessment yet. Tell me what you're "
        "trying to improve. For a neutral solo drill, try slow deliberate attempts with a full reset each time. "
        "The cue is to finish one movement before starting the next; this helps make the next recording comparable."
    )
